# كلمات صريحة تعبّر عن الشعور (بعد التطبيع). النموذج وحده أخطأ كثيراً (يرجّح joy): فإذا ذكر المستخدم شعوره صراحةً نعتمد كلامه.
EMOTION_WORDS = {
    "anger": ["غضبان", "غضبانه", "غضب", "عصبي", "عصبيه", "اعصابي", "منفعل", "منفعله", "مستفز", "مستفزه"],
    "fear": ["خايف", "خايفه", "خوف", "قلق", "قلقان", "قلقانه", "توتر", "متوتر", "متوتره", "مرعوب", "مرعوبه", "رعب", "فزعان", "فزعانه"],
    "sadness": ["حزين", "حزينه", "حزن", "مهموم", "مهمومه", "مكتئب", "مكتئبه", "مخنوق", "مخنوقه"],
    "joy": ["فرحان", "فرحانه", "فرح", "سعيد", "سعيده", "مبسوط", "مبسوطه", "نجحت", "تخرجت", "مبروك"],
}
# مواقف صعبة واضحة: لا تُعامل كفرح مهما قال النموذج
HARDSHIP_WORDS = {
    "fear": ["محتاج", "محتاجه", "رزق", "فقر", "ديون", "ايجار", "عاطل", "عاطله", "بطاله", "مفلس", "مفلسه", "وظيفه"],
    "sadness": ["مات", "ماتت", "توفي", "توفيت", "وفاه", "فقدت", "مريض", "مريضه", "مرض", "وجع"],
}
_NEG = {"ما", "مش", "لا", "مو", "ماني"}
# حيرة/ضياع بدون شعور محدد: لا نفرض عليها خوفاً أو حزناً
CONFUSION_PHRASES = ["ما عارف", "ما عارفه", "مش عارف", "مش عارفه", "حيران", "حيرانه", "محتار", "محتاره", "ضايع", "ضايعه", "تايه", "تايهه", "مشتت", "مشتته"]

def _words_hit(tokens, words):
    hit = False
    for i, w in enumerate(tokens):
        if w in words and not (i > 0 and tokens[i - 1] in _NEG):
            hit = True
    return hit

# شعور منفي ("ما غضبانة"، "ما فرحانة"): النموذج بيغلط فيها بثقة عالية (اختبار الجمل الصعبة)، فنتعامل معاها بحذر
_NEG_EMO = set(w for ws in EMOTION_WORDS.values() for w in ws) | {"زعلان", "زعلانه", "مرتاح", "مرتاحه", "متضايق", "متضايقه"}
def _negated_emotion(tokens):
    return any(w in _NEG_EMO and i > 0 and tokens[i - 1] in _NEG for i, w in enumerate(tokens))

def decide_emotion(user_input):
    tokens = re.sub(r"[^\w\s]", " ", clean_arabic_text(user_input)).split()   # نشيل علامات الترقيم عشان "غضبانة،" تتعرف
    explicit = [e for e, ws in EMOTION_WORDS.items() if _words_hit(tokens, set(ws))]
    model_emotion, conf, _ = predict_emotion(user_input)
    if _negated_emotion(tokens) and not explicit:
        return "neutral", "negation-guard", model_emotion, conf
    emotion, source = model_emotion, "model"
    if conf < CONFIDENCE_THRESHOLD:
        emotion, source = "neutral", "low-confidence"
    if len(explicit) == 1 and explicit[0] != emotion:
        emotion, source = explicit[0], "explicit-word"
    padded = " " + " ".join(tokens) + " "
    if not explicit and any(f" {p} " in padded for p in CONFUSION_PHRASES):
        return "neutral", "confusion-phrase", model_emotion, conf
    if emotion in ("joy", "neutral") and "joy" not in explicit:
        for emo, ws in HARDSHIP_WORDS.items():
            if _words_hit(tokens, set(ws)):
                emotion, source = emo, "hardship-word"
                break
    return emotion, source, model_emotion, conf

def sanad_reply(user_input, user_key="default"):
    fem = detect_female(user_input)
    if fem:
        FEM_USERS.add(user_key)
    fem = fem or (user_key in FEM_USERS)
    # 1) الطوارئ أولاً (قبل التحايا)
    is_emg, category, msg = safety_layer.check(user_input)
    if is_emg:
        return {"path": "Safety Layer", "emotion": category, "response": fill_gender(msg, fem)}
    # 2) التحايا
    is_greet, greet = check_greetings(user_input)
    if is_greet:
        return {"path": "Greeting", "emotion": "neutral", "response": fill_gender(greet, fem)}
    # 3) العاطفة (نموذج + كلمات صريحة + مواقف صعبة)
    emotion, source, model_emotion, conf = decide_emotion(user_input)
    # 4) آية منتقاة + رد متنوع
    text, verse = engine.compose(emotion, user_input, user_key, fem)
    return {"path": "SANAD Curated", "emotion": emotion, "emotion_source": source, "model_said": model_emotion,
            "confidence": conf, "verse_id": verse["id"], "response": text}

