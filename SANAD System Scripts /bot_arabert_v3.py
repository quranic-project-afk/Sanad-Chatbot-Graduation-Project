_LABELS = {0: 'fear', 1: 'joy', 2: 'anger', 3: 'sadness'}   # نفس ترتيب التدريب

def predict_emotion(text):
    """ترجع (العاطفة، الثقة كرقم بين 0 و1، تفاصيل الدرجات). هذا هو التعريف الوحيد في الدفتر."""
    e = tokenizer(str(text), truncation=True, max_length=128, return_tensors='pt').to(device)
    with torch.no_grad():
        p = torch.softmax(model(**e).logits, -1).cpu().numpy()[0]
    scores = {_LABELS[i]: float(p[i]) for i in range(4)}
    best = max(scores, key=scores.get)
    return best, round(scores[best], 4), scores

