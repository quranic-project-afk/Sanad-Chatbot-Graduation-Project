import re, random, collections

_GEN_RE = re.compile(r"\{([^{}|]*)\|([^{}|]*)\}")
def fill_gender(text, fem):
    return _GEN_RE.sub(lambda m: m.group(2) if fem else m.group(1), text)

_FEM_SET = set(FEM_MARKERS)
FEM_USERS = set()
def detect_female(text):
    words = set(clean_arabic_text(text).split())
    return bool(words & _FEM_SET)

def dedupe_sentences(t):
    seen, out = set(), []
    for s in re.split(r"(?<=[.؟!])\s+", re.sub(r"\s+", " ", t).strip()):
        k = s.strip()
        if k and k not in seen:
            seen.add(k); out.append(k)
    return " ".join(out)

def trim_tafsir(t, limit=380, hard=620):
    t = dedupe_sentences(t)
    if len(t) <= limit:
        return t
    k = t[:limit].rfind(".")
    if k > 120:
        return t[:k + 1]
    k = t.find(".", limit)          # لا نقطع الجملة في منتصفها: نكمل لنهايتها إن لم تطل
    if 0 < k <= hard:
        return t[:k + 1]
    cut = t[:limit]
    j = max(cut.rfind("،"), cut.rfind("؛"))
    return (cut[:j] if j > 120 else cut.rstrip()) + " …"

def _variants(trig):
    t = clean_arabic_text(trig)
    return [t] + [p + t for p in ("ال", "و", "ب", "ل")]

def _skel(w):
    return re.sub("[اوىيءأإآؤئةه]", "", norm_key(w))

def cut_excerpt(verse, start_phrase, end_phrase):
    """يعرض جزءاً من الآية: يطابق العبارات بهيكل الحروف فلا يتأثر بالإملاء العثماني. إن لم يجد يرجع الآية كاملة (None)."""
    words = verse.split()
    seq = [(i, _skel(w)) for i, w in enumerate(words)]
    seq = [(i, s) for i, s in seq if s]
    sk = [s for _, s in seq]
    def find(phrase, begin=0):
        p = [_skel(w) for w in phrase.split()]
        p = [s for s in p if s]
        for j in range(begin, len(sk) - len(p) + 1):
            if sk[j:j + len(p)] == p:
                return j, j + len(p) - 1
        return None
    a = find(start_phrase)
    if not a:
        return None
    first = a[0]
    if end_phrase:
        b = find(end_phrase, a[0])
        if not b:
            return None
        last = b[1]
    else:
        last = len(sk) - 1
    i0, i1 = seq[first][0], seq[last][0]
    text = " ".join(words[i0:i1 + 1])
    return ("… " if i0 > 0 else "") + text + (" …" if i1 < len(words) - 1 else "")

def select_tafsir(t, skip=0, n=None):
    sents = dedupe_sentences(t).split(" ")
    parts = re.split(r"(?<=[.؟!])\s+", dedupe_sentences(t))
    parts = parts[skip:]
    if n:
        parts = parts[:n]
    return " ".join(parts)

CALM_IDS = {"anger-7-200"}
