import re, random

def clean_arabic_text(text):
    if not isinstance(text, str):
        return ""
    text = re.sub(r"[\u064B-\u065F\u0670\u06D6-\u06ED]", "", text)
    text = re.sub(r"[إأآٱا]", "ا", text)
    text = re.sub(r"ة", "ه", text)
    text = re.sub(r"ى", "ي", text)
    return re.sub(r"\s+", " ", text).strip()

