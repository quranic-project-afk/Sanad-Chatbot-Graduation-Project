class SafetyLayer:
    def __init__(self):
        self.rules = [(cat, [re.compile(p) for p in pats]) for cat, pats in EMERGENCY_RULES]

    def check(self, text):
        norm = clean_arabic_text(text)
        for cat, pats in self.rules:          # الترتيب مقصود: إيذاء النفس أولاً ثم الطبي ثم العنف ثم الحريق
            if any(p.search(norm) for p in pats):
                return True, cat, EMERGENCY_MESSAGES[cat]
        return False, "", ""

