# ---- بناء القائمة المنتقاة: جلب نص الآية والتفسير من مصدر خارجي والتحقق من صحة كل مرجع بعبارة مفتاحية ----
import re, json, time

def norm_key(t):
    t = clean_arabic_text(t)
    return re.sub(r"[^\w\s]", "", t).replace("ـ", "")

def _skel_words(t):
    # هيكل الكلمة: حذف حروف المد والهمزات حتى لا يفشل التحقق بسبب اختلاف الإملاء العثماني/المبسّط
    return [re.sub("[اوىيءأإآؤئةه]", "", w) for w in norm_key(t).split()]

def key_in_text(key, text):
    k, t = _skel_words(key), _skel_words(text)
    return any(t[i:i + len(k)] == k for i in range(len(t) - len(k) + 1))

def strip_basmala(text):
    toks = text.split()
    if len(toks) > 4 and norm_key(" ".join(toks[:4])) == "بسم الله الرحمن الرحيم":
        return " ".join(toks[4:])
    return text

def short_surah(name):
    n = re.sub(r"[ً-ٰٟۖ-ۭ]", "", str(name)).strip()
    return re.sub(r"^سور[ةه]\s*", "", n).strip()

def fetch_ayah_api(s, a):
    """يجلب الآية (عثماني + مبسّط) وتفسيرها الميسر من alquran.cloud. يحتاج إنترنت (Colab فيه)."""
    import requests
    url = f"https://api.alquran.cloud/v1/ayah/{s}:{a}/editions/quran-uthmani,quran-simple,ar.muyassar"
    last = None
    for attempt in range(4):
        try:
            r = requests.get(url, timeout=25)
            r.raise_for_status()
            by = {d["edition"]["identifier"]: d for d in r.json()["data"]}
            return {"uth": by["quran-uthmani"]["text"], "simple": by["quran-simple"]["text"],
                    "tafsir": by["ar.muyassar"]["text"], "surah": by["quran-uthmani"]["surah"]["name"]}
        except Exception as ex:
            last = ex
            time.sleep(1.5 * (attempt + 1))
    raise RuntimeError(f"فشل جلب {s}:{a}: {last}")

def build_curated(refs_by_emotion, fetch, pause=0.15):
    cache, out, rejected = {}, {}, []
    def get(s, a):
        if (s, a) not in cache:
            cache[(s, a)] = fetch(s, a)
            time.sleep(pause)
        return cache[(s, a)]
    for emo, entries in refs_by_emotion.items():
        out[emo] = []
        for i, e in enumerate(entries):
            s, a, to = e["s"], e["a"], e.get("to", e["a"])
            try:
                parts = [get(s, k) for k in range(a, to + 1)]
            except Exception as ex:
                rejected.append({"emotion": emo, "ref": f"{s}:{a}", "reason": f"فشل الجلب: {ex}"})
                continue
            fix = (lambda t, k: strip_basmala(t) if (k == 1 and s not in (1, 9)) else t)
            uth = " ".join(fix(p["uth"], a + j) for j, p in enumerate(parts))
            simple = " ".join(fix(p["simple"], a + j) for j, p in enumerate(parts))
            if not key_in_text(e["key"], simple):
                rejected.append({"emotion": emo, "ref": f"{s}:{a}", "reason": "العبارة المفتاحية غير موجودة في النص (المرجع قد يكون خطأ)"})
                continue
            ref = f"{short_surah(parts[0]['surah'])}: {a}" + (f"-{to}" if to != a else "")
            out[emo].append({"id": f"{emo}-{s}-{a}", "ref": ref, "verse": uth, "tafsir": " ".join(dict.fromkeys(p["tafsir"] for p in parts)),
                             "theme": e["theme"], "trig": e["trig"], "story": e["story"], "gen": e["gen"], "narrow": e.get("narrow", False)})
    return {"by_emotion": out, "rejected": rejected}


