class CuratedVerseEngine:
    def __init__(self, curated, banks):
        self.by_emo = curated["by_emotion"]
        self.banks = banks
        meta = {f"{emo}-{x['s']}-{x['a']}": x for emo, lst in CURATED_REFS.items() for x in lst}   # الوسوم من القائمة الحالية (مصدر واحد للحقيقة)
        self.fallbacks = []
        for emo in list(self.by_emo):
            kept = []
            for e in self.by_emo[emo]:
                m = meta.get(e["id"])
                if not m:
                    continue                      # آية حُذفت من القائمة الحالية
                e.update(forgive=m.get("forgive", False), trig=m["trig"], story=m["story"], narrow=m.get("narrow", False), notaf=m.get("notaf", False),
                         theme=m["theme"], gen=m["gen"], taf_skip=m.get("taf_skip", 0), taf_n=m.get("taf_n"))
                e["verse"] = strip_basmala(e["verse"])
                e["shown"] = e["verse"]
                if m.get("ex"):
                    cut = cut_excerpt(e["verse"], m["ex"][0], m["ex"][1])
                    if cut:
                        e["shown"] = cut
                    else:
                        self.fallbacks.append(e["id"])   # لم نجد المقطع: نعرض الآية كاملة
                kept.append(e)
            self.by_emo[emo] = kept
        for lst in self.by_emo.values():
            for e in lst:
                pass
        for lst in self.by_emo.values():
            for e in lst:
                e["trig_v"] = [v for t in e["trig"] for v in _variants(t)]
        self.recent = collections.defaultdict(lambda: collections.deque(maxlen=8))

    def stats(self):
        return {k: len(v) for k, v in self.by_emo.items()}

    def pick(self, emotion, user_text, user_key="default", calm_only=False):
        everything = [e for lst in self.by_emo.values() for e in lst]
        if emotion in self.by_emo:
            pool = self.by_emo[emotion]
        else:
            pool = everything                      # للحالة المحايدة: كل الآيات، لكن العامة منها فقط إلا إذا طابقت كلمة
        if calm_only:                              # عند وصف أذى: آية الاستعاذة/التهدئة فقط (لا عفو ولا أمر بالصبر على الأذى)
            calm = [e for e in pool if e["id"] in CALM_IDS]
            pool = calm or pool
        norm_text = clean_arabic_text(user_text)
        padded = " " + norm_text + " "
        generic = [e for e in pool if not e.get("narrow") and (emotion in self.by_emo or e.get("gen"))]
        hits = [e for e in pool if any(f" {v} " in padded for v in e["trig_v"])]
        if hits and len(hits) >= 3 and generic and random.random() < 0.3:
            cand = generic                         # عند وجود مواضيع كثيرة مطابقة نخلط بعض الآيات العامة للتنوع
        else:
            cand = hits or generic or pool
        fresh = [e for e in cand if e["id"] not in self.recent[user_key]]
        e = random.choice(fresh or cand)
        self.recent[user_key].append(e["id"])
        return e

    def compose(self, emotion, user_text, user_key="default", fem=False):
        harm = bool(set(clean_arabic_text(user_text).split()) & HARM_WORDS) and emotion in ("anger", "sadness", "fear", "neutral")
        e = self.pick(emotion, user_text, user_key, calm_only=(harm and emotion == "anger"))
        bank = self.banks["harm"] if harm else self.banks.get(emotion, self.banks["neutral"])
        parts = [random.choice(bank["open"])]
        if e["story"] and random.random() < 0.7:
            parts.append(e["story"])
        else:
            parts.append(random.choice(bank["bridge"]))
        parts.append(f"✨ ﴿ {simplify_verse(e.get('shown', e['verse']))} ﴾\n— {e['ref']}")
        taf = "" if e.get("notaf") else trim_tafsir(select_tafsir(e["tafsir"], e.get("taf_skip", 0), e.get("taf_n")))
        if taf:
            parts.append(f"📖 من التفسير الميسر: {taf}")
        parts.append(random.choice(bank["close"]))
        if random.random() < 0.5:
            parts.append("🤲 " + random.choice(bank["dua"]))
        return fill_gender("\n\n".join(parts), fem), e

