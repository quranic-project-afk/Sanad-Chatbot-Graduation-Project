def check_greetings(user_text):
    cleaned = clean_arabic_text(user_text)
    for p in GREETINGS_PATTERNS:
        if re.search(p, cleaned) and len(cleaned.split()) <= 4:
            return True, random.choice(SUDANESE_GREETING_RESPONSES)
    return False, ""

_TAN = {"\u065E": "\u064C", "\u0656": "\u064D", "\u0657": "\u064B"}
def simplify_verse(t):
    """يحوّل التشكيل العثماني إلى تشكيل عادي ويحذف علامات الوقف، بدون حذف الحركات الأساسية."""
    t = t.replace("\u06E1", "\u0652")
    for a, b in _TAN.items():
        t = t.replace(a, b)
    t = t.replace("ٱ", "ا")
    t = re.sub("[\u06D6-\u06DC\u06DF-\u06E0\u06E2-\u06E8\u06EA-\u06ED\u0653]", "", t)   # نُبقي الهمزة (٠٦٥٤/٠٦٥٥) لأن حذفها يكسر كلمات مثل تيأسوا وشيئا
    return re.sub(r"\s+", " ", t).strip()

