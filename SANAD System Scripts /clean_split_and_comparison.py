print('torch', torch.__version__, '| transformers', transformers.__version__, '| sklearn', sklearn.__version__)
SEED = 42
def set_seed(s=SEED):
    random.seed(s); np.random.seed(s); torch.manual_seed(s); torch.cuda.manual_seed_all(s)
set_seed()
BASE = '/content/drive/My Drive'
DATA_PATH = f'{BASE}/Arabic_AraBERT_Training_Clean.csv'
PROBE_PATH = f'{BASE}/sudanese_probe.csv'       # اختياري: جمل سودانية صعبة من كتابتك (text,label,tag)
