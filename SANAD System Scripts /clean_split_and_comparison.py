MAX_LEN, EPOCHS, BATCH, LR = 128, 4, 16, 2e-5
LABELS = ['fear', 'joy', 'anger', 'sadness']; L2I = {l: i for i, l in enumerate(LABELS)}
device = torch.device('cuda' if torch.cuda.is_available() else 'cpu'); print('الجهاز:', device)

# الخلية 2: تقسيم مجمّع حسب source_row_id (أي جملتين من نفس المحادثة يروحوا لنفس القسم) + حذف المكرر
from sklearn.model_selection import StratifiedGroupKFold, train_test_split
def norm(s):
    s = re.sub(r'[\u064B-\u065F\u0670\u06D6-\u06ED]', '', str(s))
    s = re.sub(r'[إأآٱا]', 'ا', s).replace('ة', 'ه').replace('ى', 'ي')
    return re.sub(r'\s+', ' ', re.sub(r'[^\w\s]', ' ', s)).strip().lower()
raw = pd.read_csv(DATA_PATH, encoding='utf-8-sig')
df = raw[['text', 'label', 'source_row_id']].dropna().copy()
df = df[df.label.isin(LABELS)]; df['key'] = df.text.map(norm)
n0 = len(df); df = df.drop_duplicates('key').reset_index(drop=True); df['y'] = df.label.map(L2I)
print(f'حُذف {n0 - len(df)} نص مكرر | المتبقي {len(df)} | مجموعات المصدر {df.source_row_id.nunique()}')

# قياس حجم التسرب لو استخدمنا تقسيم عشوائي عادي (للتوثيق فقط)
rtr, rte = train_test_split(df, test_size=0.2, stratify=df.y, random_state=SEED)
leak = len(set(rtr.source_row_id) & set(rte.source_row_id))
print(f'⚠️ في التقسيم العشوائي العادي: {leak} مصدر بيظهر في التدريب والاختبار معاً ({(rte.source_row_id.isin(rtr.source_row_id)).mean():.1%} من الاختبار له "أخ" في التدريب)')

folds = list(StratifiedGroupKFold(n_splits=10, shuffle=True, random_state=SEED).split(df, df.y, groups=df.source_row_id))
test_idx, val_idx = folds[0][1], folds[1][1]
tr_idx = np.setdiff1d(np.arange(len(df)), np.concatenate([test_idx, val_idx]))
train_df, val_df, test_df = [df.iloc[i].reset_index(drop=True) for i in (tr_idx, val_idx, test_idx)]
g = lambda d: set(d.source_row_id)
assert not (g(train_df) & g(val_df)) and not (g(train_df) & g(test_df)) and not (g(val_df) & g(test_df)), 'تسرب مصدر!'
assert not (set(train_df.key) & set(test_df.key)) and not (set(train_df.key) & set(val_df.key)), 'تسرب نص!'
print(f'✅ لا تسرب. تدريب {len(train_df)} | تحقق {len(val_df)} | اختبار {len(test_df)}')
print(pd.DataFrame({'train': train_df.label.value_counts(), 'val': val_df.label.value_counts(), 'test': test_df.label.value_counts()}))
for n, d in [('train', train_df), ('val', val_df), ('test', test_df)]:
    d.drop(columns=['key']).to_csv(f'{OUT_DIR}/split_{n}.csv', index=False, encoding='utf-8-sig')

# الخلية 3: خط الأساس البسيط (TF-IDF + Logistic Regression) على نفس التقسيم النظيف
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, f1_score, classification_report, confusion_matrix
vec = TfidfVectorizer(ngram_range=(1, 2), min_df=2, sublinear_tf=True)
lr = LogisticRegression(max_iter=3000, C=5).fit(vec.fit_transform(train_df.key), train_df.y)
p_lr = lr.predict(vec.transform(test_df.key)); y_test = test_df.y.values
print(f'TF-IDF+LR على الاختبار النظيف: دقة {accuracy_score(y_test, p_lr):.4f} | ماكرو-F1 {f1_score(y_test, p_lr, average="macro"):.4f}')

# الخلية 4: تدريب AraBERT (حلقة PyTorch عادية، ما تعتمد على TrainingArguments عشان ما تتكسر مع تحديثات المكتبة)
from torch.utils.data import DataLoader
from transformers import AutoTokenizer, AutoModelForSequenceClassification, get_linear_schedule_with_warmup
tok = AutoTokenizer.from_pretrained(BERT_NAME)
def mk(d, shuffle):
    items = list(zip(d.text.astype(str), d.y)); gen = torch.Generator(); gen.manual_seed(SEED)
    def col(b):
        t, y = zip(*b); e = tok(list(t), padding=True, truncation=True, max_length=MAX_LEN, return_tensors='pt'); e['labels'] = torch.tensor(y); return e
    return DataLoader(items, batch_size=BATCH, shuffle=shuffle, collate_fn=col, generator=gen)
@torch.no_grad()
def predict_probs(model, texts):
    model.eval(); out = []
    for i in range(0, len(texts), 64):
        e = tok(list(texts[i:i+64]), padding=True, truncation=True, max_length=MAX_LEN, return_tensors='pt').to(device)
        out.append(torch.softmax(model(**e).logits, -1).cpu().numpy())
    return np.concatenate(out)
set_seed()
model = AutoModelForSequenceClassification.from_pretrained(BERT_NAME, num_labels=4).to(device)
tl = mk(train_df, True); opt = torch.optim.AdamW(model.parameters(), lr=LR, weight_decay=0.01)
steps = EPOCHS * len(tl); sch = get_linear_schedule_with_warmup(opt, int(.1 * steps), steps)
best, best_state = -1, None
for ep in range(1, EPOCHS + 1):
    model.train(); tot = 0
    for b in tl:
        b = {k: v.to(device) for k, v in b.items()}; loss = model(**b).loss
        opt.zero_grad(); loss.backward(); torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0); opt.step(); sch.step(); tot += loss.item()
    pv = predict_probs(model, val_df.text.values).argmax(1)
    f1v = f1_score(val_df.y, pv, average='macro')
    print(f'حقبة {ep}/{EPOCHS} | خسارة {tot/len(tl):.4f} | تحقق: دقة {accuracy_score(val_df.y, pv):.4f} ماكرو-F1 {f1v:.4f}')
    if f1v > best: best, best_state = f1v, {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
model.load_state_dict(best_state)
probs_test = predict_probs(model, test_df.text.values); p_bert = probs_test.argmax(1)
print(f'\n=== AraBERT على الاختبار النظيف (مجمّع بالمصدر) ===')
print(f'دقة {accuracy_score(y_test, p_bert):.4f} | ماكرو-F1 {f1_score(y_test, p_bert, average="macro"):.4f} | وزني-F1 {f1_score(y_test, p_bert, average="weighted"):.4f}')
print(classification_report(y_test, p_bert, target_names=LABELS, digits=3))
cm = confusion_matrix(y_test, p_bert); print(pd.DataFrame(cm, index=[f'حقيقي:{l}' for l in LABELS], columns=[f'متوقع:{l}' for l in LABELS]))
EXP = f'{OUT_DIR}/arabert_v3'; model.save_pretrained(EXP); tok.save_pretrained(EXP)
test_df.assign(pred_bert=[LABELS[i] for i in p_bert], pred_lr=[LABELS[i] for i in p_lr], conf=probs_test.max(1).round(3)).to_csv(
    f'{OUT_DIR}/test_predictions.csv', index=False, encoding='utf-8-sig')

