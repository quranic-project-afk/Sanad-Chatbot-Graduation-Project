def get_predicted_emotion(user_text):
    # تنظيف النص وتوحيد الحروف العربية الشائعة
    user_text_clean = user_text.strip().lower()
    user_text_clean = user_text_clean.replace("ة", "ه").replace("ى", "ي").replace("أ", "ا").replace("إ", "ا")

    predicted_emotion = None

    # قائمة الـ 50 كلمة مفتاحية الشاملة والموسعة للمسار الطبي (حوادث، إصابات، ألم جسدي)
    medical_keywords = [
        "اصبت", "اصابه", "حادث", "كسر", "انكسر", "مجروح", "انجرحت", "نزيف", "ينزف", "مستشفي",
        "طبيب", "دكتور", "دماء", "اسعاف", "الم", "يؤلمني", "تعبان", "مريض", "مرض", "وجع",
        "موجوع", "انكسرت", "انقلبت", "اصطدام", "دعسني", "دهس", "مصدوم", "غرق", "غرقت", "بحر",
        "اختناق", "مخنوق", "مغشي", "اغمي", "غيبوبة", "تسمم", "محروق", "احترقت", "حروق", "ضربة",
        "مضروب", "انزلاق", "سقوط", "سقطت", "وقعت", "طعن", "جرح", "عملية", "طوارئ", "عناية"
    ]

    # 1. الفحص الاستباقي الصارم لفرز المسارات الحرجة والطبية أولاً لحماية الموديل
    if any(word in user_text_clean for word in medical_keywords):
        predicted_emotion = 'medical_emergency'
    elif any(word in user_text_clean for word in ["احترق", "حريق", "نار"]):
        predicted_emotion = 'fire_emergency'
    elif any(word in user_text_clean for word in ["خايف", "قلق", "مرعوب", "حرامي", "هاجمنا", "فزع", "خطر", "تهديد", "كارثه"]):
        predicted_emotion = 'fear'
    elif any(word in user_text_clean for word in ["غضب", "اضرب", "زعلان", "بضرب", "مستفز", "عصبني", "نرفزه", "انتقام"]):
        predicted_emotion = 'anger'
    elif any(word in user_text_clean for word in ["نجحت", "فرحان", "سعيد", "سعاده", "استمتاع", "مبصوط", "مبسوط", "الحمد لله", "مبروك"]):
        predicted_emotion = 'joy'
    elif any(word in user_text_clean for word in ["حزين", "يبكي", "الحزن", "مكتئب", "تبكي", "ضيق", "وفاه", "مات", "فراق"]):
        predicted_emotion = 'sadness'

    # 2. إذا لم يعثر الفحص الاستباقي على أي كلمة مفتاحية، نلجأ للذكاء الاصطناعي
    if predicted_emotion is None:
        inputs = tokenizer(user_text, return_tensors="pt", padding=True, truncation=True, max_length=128)
        with torch.no_grad():
            outputs = model(**inputs)
        predicted_class_id = torch.argmax(outputs.logits, dim=-1).item()
        predicted_emotion = id_to_emotion[predicted_class_id]

    return predicted_emotion

