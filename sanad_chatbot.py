import pandas as pd
from sentence_transformers import SentenceTransformer, util

print("--- جاري تجهيز نظام RAG ---")

# 2. تحميل داتا سيت الماستر المدمجة التي تم إنشاؤها في الخلية السابقة
df_master = pd.read_csv('master_emotional_quran_dataset.csv')

# 3. تحميل نموذج تحويل النصوص العربية إلى Embeddings
rag_model = SentenceTransformer('sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2')

# 4. تحويل جميع النصوص (context) إلى متجهات رقمية
print("جاري تحويل النصوص إلى Vector Embeddings...")
context_embeddings = rag_model.encode(df_master['context'].tolist(), convert_to_tensor=True)

# 5. دالة الاسترجاع (Retrieval Function)
def retrieve_relevant_knowledge(user_query, top_k=2):
    query_embedding = rag_model.encode(user_query, convert_to_tensor=True)
    hits = util.semantic_search(query_embedding, context_embeddings, top_k=top_k)[0]

    results = []
    for hit in hits:
        doc_id = hit['corpus_id']
        results.append({
            'score': round(hit['score'], 3),
            'context': df_master.iloc[doc_id]['context'],
            'response': df_master.iloc[doc_id]['response'],
            'data_type': df_master.iloc[doc_id]['data_type'],
            'emotion': df_master.iloc[doc_id]['emotion']
        })
    return results

