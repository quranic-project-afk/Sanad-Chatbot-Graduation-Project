    # 3. جلب المخرجات وطباعتها هندسياً بناءً على النتيجة النهائية
    data = responses_database[predicted_emotion]

    response_parts = []
    response_parts.append(f"**⚠️ [طبيعة السياق المرصود]: {data['type']}**\n")
    response_parts.append(data['intro'].replace("{user_text}", user_text))
    response_parts.append("\n---\n")

    response_parts.append("### 📋 خطوات إجرائية فورية:\n")
    for step in data['emergency_steps']:
        response_parts.append(f"- {step}")
    response_parts.append(f"\n**__ حذف هذه العلامات __**") # Added bold and underscore for markdown
    response_parts.append("\n---\n")

    response_parts.append("### 🌿 من آيات الذكر الحكيم والتثبيت:\n")
    for verse in data['verses']:
        response_parts.append(f"- {verse}")
    response_parts.append("\n---\n")

    response_parts.append("### 🌙 من السنة النبوية وأدعية الشفاء والصبر:\n")
    for hadith in data['hadiths']:
        response_parts.append(f"- {hadith}")
    response_parts.append("\n---\n")

    response_parts.append(data['outro'])

    return "\n".join(response_parts)


