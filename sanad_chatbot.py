def generate_qwen_local_sanad(user_text, predicted_emotion="fear"):
    # أ) استرجاع المعرفة من الـ RAG
    rag_results = retrieve_relevant_knowledge(user_text, top_k=1)

    quran_context = ""
    if rag_results:
        retrieved_content = rag_results[0]['response'] if rag_results[0]['response'] != 'N/A' else rag_results[0]['context']
        quran_context = f"المعلومات المسترجعة من قاعدة المعرفة: {retrieved_content}"

    # ب) إعداد البرومبت بنظام الحوار الخاص بـ Qwen
    messages = [
        {
            "role": "system",
            "content": "أنت شات بوت 'سند'، رفيق دعم نفسي وروحي تعاطفي ولطيف جداً. تجيب باللغة العربية بأسلوب دافئ ومطمئن، وتدمج الآيات القرآنية والتفاسير المتاحة في الرد بسلاسة دون قوالب جامدة."
        },
        {
            "role": "user",
            "content": f"حالة المستخدم الشعورية: ({predicted_emotion})\nرسالة المستخدم: \"{user_text}\"\n{quran_context}"
        }
    ]

    # استخدام qwen_tokenizer المخصص
    text = qwen_tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True
    )
    model_inputs = qwen_tokenizer([text], return_tensors="pt").to(qwen_model.device)

    # ج) التوليد
    generated_ids = qwen_model.generate(
        **model_inputs,
        max_new_tokens=512,
        do_sample=True,
        temperature=0.7
    )

    generated_ids = [
        output_ids[len(input_ids):] for input_ids, output_ids in zip(model_inputs.input_ids, generated_ids)
    ]

    return qwen_tokenizer.batch_decode(generated_ids, skip_special_tokens=True)[0]

